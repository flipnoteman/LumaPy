//! Python bindings for [Luma](https://github.com/flipnoteman/Luma): lazy GPU arrays on wgpu.
//!
//! The extension module `lumapy._lumapy`; the `lumapy` Python package re-exports it and adds
//! NumPy-style conveniences. Shapes and axes are NumPy-order on the Python side and reversed
//! into Luma's order (axis 0 fastest) here, see `inner.rs`.

// Luma's handle types nest deeply (see Luma's own `recursion_limit`).
#![recursion_limit = "256"]

mod array;
mod closures;
mod context;
mod convert;
mod dtype;
mod error;
mod functions;
mod inner;
mod kernel;
mod operand;
// pyo3 expands `__add__`/`__radd__` pairs generated by `macro_rules!` into calls the 2024
// edition lint flags.
#[allow(unsafe_op_in_unsafe_fn)]
mod ops;
mod reduce;
mod scalar;
mod view;

/// The native module behind the `lumapy` package; import `lumapy`, not this module.
#[pyo3::pymodule]
mod _lumapy {
    use pyo3::prelude::*;

    #[pymodule_export]
    use crate::error::LumaError;

    #[pymodule_export]
    use crate::array::PyArr;
    #[pymodule_export]
    use crate::context::{PyContext, PyKernelTiming, PyProfile};
    #[pymodule_export]
    use crate::kernel::{PyKernel, PyUniform, PyView};
    #[pymodule_export]
    use crate::scalar::PyScalar;

    #[pymodule_export]
    use crate::closures::iterate_all;
    #[pymodule_export]
    use crate::functions::{
        asarray, bincount, concatenate, default_context, eval_all, flush, full, fusion_limit, linspace, matmul, normal,
        random_bits, range_, solve_block_tridiagonal, solve_tridiagonal, stack, uniform, where_, zeros,
    };
    #[pymodule_export]
    use crate::kernel::view;

    #[pymodule_init]
    fn init(m: &Bound<'_, PyModule>) -> PyResult<()> {
        m.add("__version__", env!("CARGO_PKG_VERSION"))?;
        // The Luma this build is compiled against (see build.rs).
        m.add("__luma_version__", env!("LUMAPY_LUMA_VERSION"))?;
        m.add("__luma_commit__", env!("LUMAPY_LUMA_COMMIT"))?;
        m.add("__luma_source__", env!("LUMAPY_LUMA_SOURCE"))
    }
}
